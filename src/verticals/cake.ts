import type { OptionGroup, Product, VerticalConfig } from "../shop-core/types.ts";

/** Price is per base weight; heavier cakes add the per-kilo price for each extra kilo. */
function cakeOptions(perKg: number, weights: number[]): OptionGroup[] {
  const base = weights[0]!;
  return [
    {
      id: "weight",
      label: "Քաշ",
      kind: "choice",
      choices: weights.map((kg) => ({
        id: String(kg),
        label: `${kg} կգ`,
        priceDelta: (kg - base) * perKg,
      })),
    },
    {
      id: "filling",
      label: "Միջուկ",
      kind: "choice",
      choices: [
        { id: "vanilla", label: "Վանիլ" },
        { id: "choco", label: "Շոկոլադ" },
        { id: "berry", label: "Ելակ", priceDelta: 1500 },
      ],
    },
    {
      id: "inscription",
      label: "Մակագրություն տորթի վրա",
      kind: "text",
      personal: true,
      placeholder: "Օր.՝ Շնորհավոր, Արամ",
      maxLength: 30,
    },
    { id: "date", label: "Երբ է պետք", kind: "date", personal: true },
  ];
}

const p = (product: Omit<Product, "options" | "unit">, perKg: number, weights = [1, 2, 3]): Product => ({
  ...product,
  options: cakeOptions(perKg, weights),
  unit: `${weights[0]} կգ`,
});

